const PLACEHOLDER = /\$\{(\d+)\}/g;
const exact = new Map();
// Notices with changing parts: their English as a pattern, the parts carried into the Korean
const patterns = [];
for (const [english, korean] of Object.entries(TOASTS)) {
    if (!english.includes('${')) {
        exact.set(english, korean);
        continue;
    }
    const order = [];
    const source = english.split(PLACEHOLDER).map((part, index) => {
        if (index % 2) {
            order.push(Number(part));
            return '([\\s\\S]*?)';
        }
        return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    }).join('');
    patterns.push({ regex: new RegExp(`^${source}$`), order, korean });
}

/** The Korean of a notice's text, or the text as it was. */
export function toastKorean(text) {
    if (typeof text !== 'string' || !text) {
        return text;
    }
    const trimmed = text.trim();
    const found = exact.get(trimmed);
    if (found !== undefined) {
        return found;
    }
    for (const { regex, order, korean } of patterns) {
        const match = trimmed.match(regex);
        if (match) {
            const parts = new Map(order.map((slot, index) => [slot, match[index + 1]]));
            return korean.replace(PLACEHOLDER, (_, slot) => parts.get(Number(slot)) ?? '');
        }
    }
    return text;
}

let patched = false;

/** Notices get their Korean as they are shown (message and title). */
export function translateToasts() {
    const toastr = window.toastr;
    if (patched || !toastr) {
        return;
    }
    patched = true;
    for (const kind of ['success', 'info', 'warning', 'error']) {
        const original = toastr[kind];
        if (typeof original !== 'function') {
            continue;
        }
        toastr[kind] = function (message, title, ...rest) {
            return original.call(this, toastKorean(message), toastKorean(title), ...rest);
        };
    }
}
